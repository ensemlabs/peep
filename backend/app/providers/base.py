import io
import uuid
from typing import TYPE_CHECKING, Any, Protocol

if TYPE_CHECKING:
    from app.services.runs import RunState


class ProviderError(Exception):
    """A failure the user should see as the message's error text (not a server bug)."""


def new_id() -> str:
    return uuid.uuid4().hex[:12]


class RunContext:
    """What a provider gets: where it is running and how to emit parts."""

    def __init__(
        self,
        state: "RunState",
        *,
        user_id: uuid.UUID,
        conversation_id: uuid.UUID,
        user_message_id: uuid.UUID,
        model: str,
        reasoning: bool,
    ):
        self.state = state
        self.user_id = user_id
        self.conversation_id = conversation_id
        self.user_message_id = user_message_id
        self.message_id = state.message_id
        self.model = model
        self.reasoning = reasoning

    async def emit_part(self, part: dict[str, Any], parent_id: str | None = None) -> dict[str, Any]:
        return await self.state.emit_part(part, parent_id)

    async def emit_delta(self, part_id: str, field: str, text: str) -> None:
        await self.state.emit_delta(part_id, field, text)

    async def emit_update(self, part_id: str, patch: dict[str, Any]) -> None:
        await self.state.emit_update(part_id, patch)

    async def store_file(self, data: bytes, mime: str, filename: str) -> dict[str, Any]:
        """Persist generated bytes (S3 + files row) and return the FileMeta dict."""
        from app.db import get_sessionmaker
        from app.services import media

        async with get_sessionmaker()() as db:
            row = await media.ingest(
                db,
                user_id=self.user_id,
                fp=io.BytesIO(data),
                size=len(data),
                filename=filename,
                mime=mime,
                source="generated",
                conversation_id=self.conversation_id,
                message_id=self.message_id,
            )
        return media.file_meta(row)


class Provider(Protocol):
    async def run(self, ctx: RunContext) -> None: ...
